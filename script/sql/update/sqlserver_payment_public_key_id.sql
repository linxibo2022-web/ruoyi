-- 变更内容：
--   b_payment 新增 public_key_id 字段（微信支付 V3 公钥模式专用）
-- 触发原因：
--   微信支付 V3「公钥模式」验签需要独立的公钥ID(PUB_KEY_ID_xxx)，
--   原实现误用证书序列号(cert_serial_no)冒充，导致公钥模式验签失败。
-- 引入版本：2026-05 同步批次
-- 升级前请备份 b_payment 表！
-- ============================================================================

ALTER TABLE b_payment ADD public_key_id NVARCHAR(100) NULL;
GO

-- 列注释（扩展属性）
EXEC sys.sp_addextendedproperty
     'MS_Description', N'微信支付公钥ID(V3公钥模式专用,格式 PUB_KEY_ID_xxx)',
     'SCHEMA', N'dbo',
     'TABLE', N'b_payment',
     'COLUMN', N'public_key_id';
GO

